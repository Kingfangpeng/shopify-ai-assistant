test('深度分析停止会取消后台流并保存中断状态', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('用户名').fill('king')
  await page.getByLabel('密码').fill('Local-QA-Password-2026')
  await page.getByRole('button', { name: '进入运营台' }).click()
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  await page.getByRole('button', { name: '深度分析', exact: true }).click()
  await page.getByLabel('输入问题').fill('停止测试：分析订单')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByText('初始计划')).toBeVisible()
  await page.getByRole('button', { name: '停止生成' }).click()
  await expect(page.getByText('深度分析 · 分析已中断')).toBeVisible()
  await expect.poll(async () => {
    const list = await (await page.request.get('/api/chat/sessions')).json()
    const detail = await (await page.request.get(`/api/chat/sessions/${list.items[0].id}`)).json()
    return detail.messages.at(-1)?.status
  }).toBe('interrupted')
  await page.reload()
  await expect(page.getByText('深度分析 · 分析已中断')).toBeVisible()
  await expect(page.getByRole('button', { name: '重试', exact: true })).toBeVisible()
})
