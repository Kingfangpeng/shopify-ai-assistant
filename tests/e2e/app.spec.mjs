  await expect(page).toHaveURL(/\/chat$/)
  await expect(page.getByLabel('选择对话模型')).toHaveValue('e2e-fast')
  await page.getByLabel('选择对话模型').selectOption('e2e-accurate')

  await page.getByLabel('输入问题').fill('今天出了几单')
  await page.getByRole('button', { name: '发送' }).click()
  await expect(page.getByText('订单汇总 ✓')).toBeVisible()
  await expect(page.getByText(/订单概况：342 单/)).toBeVisible()
  await expect(page.getByText('演示数据')).toBeVisible()

  await page.getByRole('link', { name: '知识库' }).click()
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('button', { name: '上传文档' }).click()
  await (await chooser).setFiles(fixture)
  await expect(page.getByText('product.md 已安全索引')).toBeVisible()
  await page.getByRole('button', { name: /product\.md 1 个分片/ }).click()
  await expect(page.getByText(/24 小时保冷/)).toBeVisible()
